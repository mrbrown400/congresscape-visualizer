function readCommand(command, args) {
  return execFileSync(command, args, { encoding: 'utf8' }).trim();
}

function readJsonIfExists(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }
  return JSON.parse(readFileSync(filePath, 'utf8'));
}

function formatScripts(scripts = {}, prefix = '') {
  const entries = Object.entries(scripts);
  if (!entries.length) {
    return ['- none'];
  }
  return entries.map(([name, command]) => {
    const display = prefix ? `(from ${prefix.slice(0, -1)}) npm run ${name}` : `npm run ${name}`;
    return `- \`${display}\`: \`${command}\``;
  });
}

function formatBackendCommands(pyprojectText) {
  const hasPoetry = pyprojectText.includes('[tool.poetry]');
  if (!hasPoetry) {
    return ['- backend Poetry project not detected'];
  }
  return [
    '- `(from backend) poetry install`: install backend dependencies.',
    '- `(from backend) poetry run python -m app.db.init_db`: initialize the configured database schema.',
    '- `(from backend) poetry run uvicorn app.main:app --reload`: start the FastAPI dev server.',
    '- `(from backend) poetry run pytest`: run backend tests.',
    '- `(from backend) poetry run ruff check .`: run backend lint checks.'
  ];
}

function summarizeFiles(files) {
  const groups = [
    ['`backend/app/api/routes/`', startsWithCount(files, 'backend/app/api/routes/')],
    ['`backend/app/services/`', startsWithCount(files, 'backend/app/services/')],
    ['`backend/app/ingest/`', startsWithCount(files, 'backend/app/ingest/')],
    ['`backend/app/models/`', startsWithCount(files, 'backend/app/models/')],
    ['`backend/app/schemas/`', startsWithCount(files, 'backend/app/schemas/')],
    ['`backend/tests/`', startsWithCount(files, 'backend/tests/')],
    ['`frontend/src/features/`', startsWithCount(files, 'frontend/src/features/')],
    ['`frontend/src/components/`', startsWithCount(files, 'frontend/src/components/')],
    ['`frontend/src/services/`', startsWithCount(files, 'frontend/src/services/')],
    ['`frontend/src/navigation/`', startsWithCount(files, 'frontend/src/navigation/')],
    ['`frontend/src/theme/`', startsWithCount(files, 'frontend/src/theme/')],
    ['`docs/`', startsWithCount(files, 'docs/')],
    ['`docs/agentic/`', startsWithCount(files, 'docs/agentic/')],
    ['`.agents/skills/`', startsWithCount(files, '.agents/skills/')]
  ];

  return groups.map(([label, count]) => `- ${label}: ${count} known files`);
}

function startsWithCount(files, prefix) {
  return files.filter((filePath) => filePath.startsWith(prefix)).length;
}
